#!/usr/bin/env python3
"""Convert the combinational anlogic_logo_rom case table into a BRAM .mif.

my_osd.v implements the example-project logo as a giant `case` on a linear
address y*160+x, which costs roughly one gate per non-zero pixel.  This script
emits the identical contents as a 160x160x25 initialised block RAM, so the
picture is unchanged but the cost drops from ~61k gates to one block RAM.

bit[24] is the valid/opaque flag and bits[23:0] are RGB888, matching the
original module port width.
"""

from __future__ import annotations

import argparse
import pathlib
import re


ENTRY_RE = re.compile(r"15'd(\d+)\s*:\s*O_pixel\s*=\s*25'h([0-9a-fA-F]+)")
LOGO_W = 160
LOGO_H = 160


def main() -> None:
    ap = argparse.ArgumentParser()
    ap.add_argument("--osd", required=True, help="path to my_osd.v")
    ap.add_argument("--out", required=True, help="output .mif path")
    args = ap.parse_args()

    osd = pathlib.Path(args.osd)
    src = osd.read_text(encoding="utf-8", errors="ignore")
    idx = src.find("module anlogic_logo_rom")
    if idx < 0:
        raise SystemExit("anlogic_logo_rom module not found")

    entries = [(int(a, 10), int(b, 16)) for a, b in ENTRY_RE.findall(src[idx:])]
    if not entries:
        raise SystemExit("no case entries parsed")

    table: dict[int, int] = {}
    out_of_range = 0
    for addr, val in entries:
        y, x = divmod(addr, LOGO_W)
        if y >= LOGO_H or x >= LOGO_W:
            out_of_range += 1
            continue
        table[y * LOGO_W + x] = val

    colors = collections.Counter(table.values())
    nonzero = len(table)
    print(f"parsed {len(entries)} case entries")
    print(f"in-range non-zero pixels: {nonzero} / {LOGO_W * LOGO_H} "
          f"({100.0 * nonzero / (LOGO_W * LOGO_H):.1f}%)")
    print(f"out-of-range entries skipped: {out_of_range}")
    print(f"distinct colours: {len(colors)}")
    print(f"BRAM cost: {LOGO_W * LOGO_H} x 25bit = "
          f"{(LOGO_W * LOGO_H * 25 + 1023) // 1024} Kbit")

    out = pathlib.Path(args.out)
    out.parent.mkdir(parents=True, exist_ok=True)
    depth = 1
    while depth < LOGO_W * LOGO_H:
        depth *= 2
    with out.open("w", encoding="ascii", newline="\n") as fh:
        fh.write("-- auto-generated by tools/gen_logo_rom_mif.py, do not edit\n")
        fh.write("-- source: user_source/hdl_source/my_algo/my_osd.v (combinational case)\n")
        fh.write("-- 160x160, bit[24]=valid, bits[23:0]=RGB888\n")
        fh.write("WIDTH = 25;\n")
        fh.write(f"DEPTH = {depth};\n")
        fh.write("ADDRESS_RADIX = DEC;\n")
        fh.write("DATA_RADIX = HEX;\n")
        fh.write("CONTENT BEGIN\n")
        for off in range(LOGO_W * LOGO_H):
            fh.write(f"  {off:5d} : {table.get(off, 0):06x};\n")
        fh.write("END;\n")
    print(f"wrote {out}")


if __name__ == "__main__":
    main()
